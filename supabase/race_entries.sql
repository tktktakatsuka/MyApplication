-- 今週の出走馬（出馬表）テーブル
-- アプリの「今週の出走馬」画面がこのテーブルを読む。
-- 収集バッチ（C:/work/batch の entries コマンド）が、開催の数日前から1頭1行で登録する。
-- 特別登録の段階では枠・馬番・騎手が空で、木〜金曜の出馬表確定・枠順確定後に埋まる。
-- 再実行のたびに、その開催日・競馬場の行を削除してから入れ直す（出走取消などもこれで反映される）。
--   kaisaibi     開催日 yyyyMMdd（race_results と同じ形式）
--   kaisaijo     競馬場名（"東京" など、race_results と同じ表記）
--   race_no      レース番号 1〜12
--   race_title   レース名
--   race_info    条件・距離など（"オープン (国)(指) 別定 芝1600m 14頭 発走" など、自由形式）
--   waku         枠番（枠順確定前は空）
--   horse_number 馬番（枠順確定前は空）
--   horse_name   馬名（(外)(地) などの印なし。race_results.horse_name と照合して過去成績を出す）
--   sex_age      性齢
--   jockey       騎手（出馬表確定前は空）
--   weight       斤量
--   trainer      調教師
--   win_odds     単勝オッズ（"5.3"。出馬表の取り込み時と、開催日の30分ごとの更新で入る。発売前・取消は空）
--   popular      単勝人気（オッズの低い順。発売前・取消は空）
--   odds_updated_at オッズを取り込んだ日時

create table if not exists public.race_entries (
    id           bigint generated by default as identity primary key,
    kaisaibi     text    not null,
    kaisaijo     text    not null,
    race_no      integer not null,
    race_title   text,
    race_info    text,
    waku         text,
    horse_number text,
    horse_name   text    not null,
    sex_age      text,
    jockey       text,
    weight       text,
    trainer      text,
    win_odds     text,
    popular      text,
    odds_updated_at timestamptz,
    created_at   timestamptz not null default now(),
    unique (kaisaibi, kaisaijo, race_no, horse_name)
);

-- すでに古い定義でテーブルを作っていた場合の列追加
alter table public.race_entries add column if not exists sex_age text;
alter table public.race_entries add column if not exists trainer text;
alter table public.race_entries add column if not exists win_odds text;
alter table public.race_entries add column if not exists popular text;
alter table public.race_entries add column if not exists odds_updated_at timestamptz;

create index if not exists race_entries_kaisaibi_idx on public.race_entries (kaisaibi);

-- アプリ（publishable key）からは読み取りだけ許可する。
-- 書き込みは収集バッチが secret キーで行う（secret キーは RLS の対象外なので書き込み用のポリシーは不要）。
alter table public.race_entries enable row level security;

drop policy if exists "race_entries are readable by everyone" on public.race_entries;
create policy "race_entries are readable by everyone"
    on public.race_entries for select
    using (true);

-- 過去成績の検索を速くする
create index if not exists race_results_horse_name_idx on public.race_results (horse_name);
